using System.Security.Cryptography;
using OptimizadorPC.Optimizaciones.FiveM;
using OptimizadorPC.Pruebas.Infra;

namespace OptimizadorPC.Pruebas
{
    [Collection("Sistema")]
    public class TexturasAutosPruebas
    {
        [Fact]
        public void LosComandosSonLosOficialesYSeDeshacen()
        {
            Assert.Equal("seta str_maxVehicleTextureRes 512", TexturasAutos.ComandoRecomendado);
            Assert.Equal("seta str_maxVehicleTextureRes 1024", TexturasAutos.ComandoPorDefecto);   // el defecto documentado
            Assert.Equal(1024, TexturasAutos.PorDefecto);
        }

        [Theory]
        [InlineData("seta \"str_maxVehicleTextureRes\" \"1024\"", 1024)]   // como lo escribe FiveM
        [InlineData("seta str_maxVehicleTextureRes 512", 512)]             // como lo escribe una persona
        [InlineData("set \"str_maxVehicleTextureRes\" \"768\"", 768)]
        [InlineData("seta \"str_maxVehicleTextureResRgba\" \"512\"", null)] // otra variable que empieza igual
        [InlineData("// seta str_maxVehicleTextureRes 256", null)]          // comentada
        [InlineData("seta \"cl_drawFPS\" \"false\"", null)]
        public void LeerValor_UnaLinea(string linea, int? esperado)
        {
            Assert.Equal(esperado, LeerDe($"// generated by CitizenFX\r\nunbindall\r\n{linea}\r\n"));
        }

        [Fact]
        public void LeerValor_LaUltimaGana()
        {
            Assert.Equal(512, LeerDe("seta \"str_maxVehicleTextureRes\" \"1024\"\r\nseta str_maxVehicleTextureRes 512\r\n"));
        }

        [Fact]
        public void LeerValor_SinArchivo()
        {
            Assert.Null(TexturasAutos.LeerValor(Path.Combine(Path.GetTempPath(), $"no-existe-{Guid.NewGuid():N}.cfg")));
        }

        [Fact]
        public void LeerValor_ElFivemCfgRealSoloSeLee()
        {
            if (!File.Exists(TexturasAutos.ArchivoCfg))
            {
                return;   // PC donde FiveM nunca se abrió: no hay nada que leer
            }
            byte[] antes = SHA256.HashData(File.ReadAllBytes(TexturasAutos.ArchivoCfg));
            DateTime fechaAntes = File.GetLastWriteTimeUtc(TexturasAutos.ArchivoCfg);

            int? valor = TexturasAutos.LeerValor(TexturasAutos.ArchivoCfg);

            Assert.True(valor is null or > 0);
            Assert.Equal(antes, SHA256.HashData(File.ReadAllBytes(TexturasAutos.ArchivoCfg)));
            Assert.Equal(fechaAntes, File.GetLastWriteTimeUtc(TexturasAutos.ArchivoCfg));
        }

        [Fact]
        public void LaPantallaFiveMUsaLosComandosDeTexturasAutos()
        {
            string xaml = File.ReadAllText(Path.Combine(RaizRepositorio(), "Paginas", "FiveMPagina.xaml"));
            Assert.Contains("{x:Static fivem:TexturasAutos.ComandoRecomendado}", xaml);
            Assert.Contains("{x:Static fivem:TexturasAutos.ComandoPorDefecto}", xaml);
        }

        private static int? LeerDe(string contenido)
        {
            string carpeta = Ayudas.CarpetaTemporal();
            try
            {
                string cfg = Path.Combine(carpeta, "fivem.cfg");
                File.WriteAllText(cfg, contenido);
                return TexturasAutos.LeerValor(cfg);
            }
            finally
            {
                Directory.Delete(carpeta, recursive: true);
            }
        }

        private static string RaizRepositorio([System.Runtime.CompilerServices.CallerFilePath] string archivo = "") =>
            Path.GetFullPath(Path.Combine(Path.GetDirectoryName(archivo)!, "..", ".."));
    }
}
